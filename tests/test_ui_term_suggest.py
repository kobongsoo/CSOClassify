# -*- coding: utf-8 -*-
#------------------------------------------------------------------
# 검토 화면의 '단어 제안' 표기 — ui/uiwords.py 단위 시험
#=> 후보를 뽑는 계산은 test_termsuggest.py 가 본다. 여기서는 그 결과를 사람에게
#   어떻게 말하는지만 본다. 관리자가 체크를 켤지 말지 판단할 재료는 이 한 줄뿐이라,
#   개발 용어(title_terms·df_neg)가 새어 나가지 않는지·경고가 빠지지 않는지를 지킨다.
#   Streamlit 은 거치지 않는다(순수 문자열 함수).
#------------------------------------------------------------------

import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(_HERE, "..", "ui"))

import uiwords as W   # noqa: E402


#------------------------------------------------------------------
# 후보 하나 만들기 (시험용)
#=> termsuggest 가 내는 모양에서 표기에 쓰이는 칸만 채운다.
#
# -in: fields·docs·clusters·df_neg·flags·extra = 표기에 쓰는 값들
#
# -out: dict = 후보 dict
# -out: error = 없음
#------------------------------------------------------------------
def cand(fields=("title_terms", "filename"), docs=6, clusters=2, df_neg=0.0,
         flags=(), extra=None):
    return {"term": "품목보고서", "fields": list(fields), "docs": docs,
            "clusters": clusters, "df_neg": df_neg, "flags": list(flags),
            "extra": dict(extra or {})}


#------------------------------------------------------------------
# 칸 이름은 사람 말로 나간다
#=> 화면에 title_terms 가 보이면 관리자는 그것이 무엇인지 알 수 없다.
#------------------------------------------------------------------
def test_칸_이름은_사람말로():
    got = W.suggest_where(["title_terms", "filename"])
    assert "제목" in got and "파일 이름" in got
    assert "title_terms" not in got
    assert "filename" not in got


#------------------------------------------------------------------
# 칸이 없으면 빈 문자열
#------------------------------------------------------------------
def test_칸이_없으면_빈줄():
    assert W.suggest_where([]) == ""
    assert W.suggest_where(None) == ""


#------------------------------------------------------------------
# 근거는 건수·폴더 수·다른 분류 비율을 모두 말한다
#=> 셋 중 하나만 보여 주면 판단이 갈린다. '6건'만 보면 한 폴더에서 나온 6건인지
#   알 수 없고, 폴더만 보면 얼마나 흔한 말인지 알 수 없다.
#------------------------------------------------------------------
def test_근거는_세_가지를_모두_말한다():
    got = W.suggest_why(cand(docs=6, clusters=2, df_neg=0.0))
    assert "6건" in got
    assert "폴더 2곳" in got
    assert "0.0%" in got
    assert "df_neg" not in got          # 개발 용어는 안 나간다


#------------------------------------------------------------------
# 경고 표식은 빠짐없이 나간다
#=> '흔한 말'·'고유명사 의심'은 체크를 켜지 말라는 신호다. 숨기면 안 된다.
#------------------------------------------------------------------
def test_경고는_빠지지_않는다():
    got = W.suggest_why(cand(flags=["흔한 말", "고유명사 의심"]))
    assert "흔한 말" in got
    assert "고유명사 의심" in got


#------------------------------------------------------------------
# 본문 칸이면 '몇 회 이상일 때만 인정'을 함께 말한다
#=> min_count 가 조용히 붙으면, 나중에 규칙을 열어 본 사람이 "이 값 누가 넣었지"
#   하게 된다.
#------------------------------------------------------------------
def test_본문칸은_최소_횟수를_말한다():
    got = W.suggest_why(cand(fields=["terms"], extra={"min_count": 2}))
    assert "2회 이상" in got


#------------------------------------------------------------------
# 값이 없어도 깨지지 않는다
#=> 후보 dict 의 칸이 비어 있어도 화면은 떠야 한다.
#------------------------------------------------------------------
def test_빈_후보도_깨지지_않는다():
    got = W.suggest_why({})
    assert "0건" in got


#------------------------------------------------------------------
# 단어 결정 이력의 동작은 사람 말로 나간다
#=> 'accept'/'reject' 를 그대로 보여주면 관리자가 무슨 뜻인지 알 수 없다.
#------------------------------------------------------------------
def test_결정_동작은_사람말로():
    assert W.suggest_action("accept") == "기준에 넣음"
    assert W.suggest_action("reject") == "다시 보지 않음"


#------------------------------------------------------------------
# 모르는 값이 와도 화면이 깨지지 않는다
#=> 이력은 append-only 라 옛 줄에 모르는 값이 남아 있을 수 있다.
#------------------------------------------------------------------
def test_모르는_동작도_그대로_보여준다():
    assert W.suggest_action("무언가") == "무언가"
    assert W.suggest_action(None) == ""


#------------------------------------------------------------------
# 꼬리표에 HTML 을 쓰지 않는다
#=> streamlit 의 체크박스 라벨은 마크다운만 읽고 HTML 태그는 글자 그대로 찍는다.
#   <span> 을 넣었다가 라벨에 태그가 그대로 보인 일이 있다(2026-09-16).
#------------------------------------------------------------------
def test_꼬리표에_HTML_이_없다():
    got = W.suggest_where(["title_terms", "filename"])
    assert "<" not in got and ">" not in got
