#------------------------------------------------------------------
# 분류 결과 집계(summary.py) 단위 테스트 — 설계서 §7-3
#=> 보안등급 집계, 업무분류 롤업(뿌리별 + 노드별 내역), doctype 축이 안 돌았을
#   때 그 섹션을 완전히 빼는지, 다중라벨로 합계가 총건수를 넘을 때 안내
#   문구가 붙는지 검증한다.
#------------------------------------------------------------------

from csoclassify.classify import summarize_records


#------------------------------------------------------------------
# 최소 레코드 만들기
#
# -in: security = 보안등급 값(None 가능)
# -in: doctype  = labels.doctype dict(None 이면 labels 에 doctype 키 자체를 안 만듦)
#
# -out: dict = summarize_records 가 읽는 최소 레코드
# -out: error = 없음
#------------------------------------------------------------------
def mk(security=None, doctype=None):
    labels = {"security": {"value": security}}
    if doctype is not None:
        labels["doctype"] = doctype
    return {"labels": labels}


#------------------------------------------------------------------
# doctype 값 dict 헬퍼
#
# -in: pairs = [(dc_id, path), ...]
#
# -out: dict = {"values": [{"dc_id":..., "path":...}, ...]}
# -out: error = 없음
#------------------------------------------------------------------
def dt(*pairs):
    return {"values": [{"dc_id": dc_id, "path": path} for dc_id, path in pairs]}


# ── 보안등급 집계 ────────────────────────────────────────────────

#------------------------------------------------------------------
# 등급별 건수와 미분류 건수가 정확히 집계된다
#
# -in: 없음
# -out: 없음(단언)
# -out: error = 없음
#------------------------------------------------------------------
def test_보안등급_집계():
    records = [mk("C"), mk("C"), mk("S"), mk("O"), mk(None)]
    text = summarize_records(records)
    assert "총 5건" in text
    assert "C 2 · S 1 · O 1 · 미분류 1" in text


#------------------------------------------------------------------
# 하위호환 — labels 없이 grade 만 있는 옛 레코드도 집계된다
#
# -in: 없음
# -out: 없음(단언)
# -out: error = 없음
#------------------------------------------------------------------
def test_labels_없는_구버전_레코드도_집계():
    records = [{"grade": "C"}, {"grade": None}]
    text = summarize_records(records)
    assert "C 1 · S 0 · O 0 · 미분류 1" in text


# ── 업무분류 롤업 ────────────────────────────────────────────────

#------------------------------------------------------------------
# doctype 축이 한 건도 안 돌았으면 업무분류 섹션 자체가 없다
#
# -in: 없음
# -out: 없음(단언)
# -out: error = 없음
#------------------------------------------------------------------
def test_doctype_축_안돌면_섹션_없음():
    records = [mk("C"), mk("S")]
    text = summarize_records(records)
    assert "업무분류" not in text


#------------------------------------------------------------------
# 뿌리별로 롤업되고, 뿌리 안에서는 실제 걸린 노드 이름별로 내역이 붙는다
#
# -in: 없음
# -out: 없음(단언)
# -out: error = 없음
#------------------------------------------------------------------
def test_업무분류_뿌리별_롤업():
    records = [
        mk("O", dt(("D1", "기술/개발 > 설계문서"))),
        mk("O", dt(("D2", "기술/개발 > 매뉴얼"))),
        mk("O", dt(("D3", "기술/개발 > 매뉴얼"))),
        mk("S", dt(("L1", "법무/규정 > 계약서"))),
        mk("O", None),   # doctype 축은 돌았으나(labels.doctype 없음) → 이 레코드는 집계 제외
        mk("O", dt()),   # 축은 돌았는데 후보가 없음 → 미분류
    ]
    text = summarize_records(records)
    assert "기술/개발 3 (매뉴얼 2 · 설계문서 1)" in text
    assert "법무/규정 1 (계약서 1)" in text
    assert "미분류 1" in text


#------------------------------------------------------------------
# 한 문서가 여러 분류를 가지면 합계가 총건수를 넘고, 안내 문구가 붙는다
#
# -in: 없음
# -out: 없음(단언)
# -out: error = 없음
#------------------------------------------------------------------
def test_다중라벨은_합계가_총건수보다_크면_안내문구():
    records = [
        mk("S", dt(("L1", "법무/규정 > 계약서"), ("P1", "영업/마케팅 > 제안서"))),
    ]
    text = summarize_records(records)
    assert "법무/규정 1 (계약서 1)" in text
    assert "영업/마케팅 1 (제안서 1)" in text
    assert "합계(2)가 총건수(1)보다 큰 것은 정상" in text


#------------------------------------------------------------------
# 단일라벨만 있으면(합계==총건수) 안내 문구가 붙지 않는다
#
# -in: 없음
# -out: 없음(단언)
# -out: error = 없음
#------------------------------------------------------------------
def test_단일라벨만_있으면_안내문구_없음():
    records = [mk("S", dt(("L1", "법무/규정 > 계약서")))]
    text = summarize_records(records)
    assert "정상" not in text
