#------------------------------------------------------------------
# 사람이 고친 등급을 문서에 다시 잇기 — 결합 키 계약 (2026-09-10)
#=> doc_id 가 sfile_id 전용이 되면서, '문서를 옮겨도 수정이 따라오게' 하는
#   몫이 hash 로 넘어갔다. 이 결합이 끊기면 오류는 안 나고 사람이 고쳐 둔
#   등급만 조용히 사라진다 — 거버넌스 도구에서 가장 나쁜 실패라 시험으로 묶는다.
#
#   [매칭 차례] ① doc_id(sfile_id) ② 지문 ③ 정규화 경로 ④ 대소문자 ⑤ 새 문서
#------------------------------------------------------------------

import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(_HERE, "..", "ui"))

import docidkey                                              # noqa: E402


# 시험용 지문(SHA-256 길이 64자). 옛 기록은 이 값의 앞 40자를 doc_id 로 갖고 있었다.
H = "2cf24dba5fb0a30e26e83b2ac5b9e29e1b161e5c1fa7425e73043362938b9824"


#------------------------------------------------------------------
# 지문으로 이으면 폴더를 옮겨도 수정이 따라온다
#=> 목록(--filelist) 없이 도는 실행에서는 doc_id 가 늘 None 이라, 이 길이
#   유일하게 '경로가 바뀌어도 살아남는' 결합이다.
#------------------------------------------------------------------
def test_지문으로_이으면_옮겨도_따라온다():
    idx = docidkey.OverrideIndex({"D:/옛폴더/a.doc": {"doc_id": None, "hash": H}})
    got, how = idx.resolve({"file": "D:/새폴더/a.doc", "hash": H})
    assert (got, how) == ("D:/옛폴더/a.doc", "hash")


#------------------------------------------------------------------
# sfile_id 가 있으면 그것이 우선이다
#=> 번호는 시스템이 정한 정체성이라 내용을 고쳐도 안 변한다. 지문보다 세다.
#------------------------------------------------------------------
def test_sfile_id_가_지문보다_우선이다():
    idx = docidkey.OverrideIndex({"D:/옛폴더/c.doc": {"doc_id": "SF-1", "hash": "다른지문"}})
    got, how = idx.resolve({"file": "D:/새폴더/c.doc", "doc_id": "SF-1", "hash": H})
    assert (got, how) == ("D:/옛폴더/c.doc", "doc_id")


#------------------------------------------------------------------
# 2026-09-10 이전에 쌓은 기록도 이어진다 <중요>
#=> 그때는 doc_id 칸에 '지문 앞 40자'가 들어 있었다. 이 호환이 빠지면
#   그동안 사람이 고쳐 둔 등급이 통째로 새 문서 취급된다.
#------------------------------------------------------------------
def test_옛_기록도_지문으로_이어진다():
    idx = docidkey.OverrideIndex({"D:/옛폴더/b.doc": {"doc_id": H[:40]}})
    got, how = idx.resolve({"file": "D:/새폴더/b.doc", "hash": H})
    assert (got, how) == ("D:/옛폴더/b.doc", "hash")


#------------------------------------------------------------------
# 내용이 바뀌면 지문으로는 안 이어진다 — 그게 맞다
#=> 내용이 달라진 문서에 옛 판단을 그대로 붙이면 안 된다. 경로가 같으면
#   경로로 잇고(사람이 다시 본다), 경로도 다르면 새 문서다.
#------------------------------------------------------------------
def test_내용이_바뀌면_지문으로는_안_이어진다():
    idx = docidkey.OverrideIndex({"D:/옛폴더/d.doc": {"doc_id": None, "hash": H}})
    # 경로가 같으면 경로로 이어진다(정확히 같은 키라 how 는 None).
    got, _how = idx.resolve({"file": "D:/옛폴더/d.doc", "hash": "ffff"})
    assert got == "D:/옛폴더/d.doc"
    # 경로도 다르면 새 문서다 — 남의 수정을 붙이지 않는다.
    assert idx.resolve({"file": "D:/전혀/다른.doc", "hash": "ffff"}) == (None, None)


#------------------------------------------------------------------
# key 칸이 없어도 경로 결합이 그대로 된다
#=> 레코드에서 key 를 뺐다(file 로 그때그때 만든다). 그 때문에 경로로 잇던
#   길이 끊기지 않았는지 확인한다.
#------------------------------------------------------------------
def test_key_칸이_없어도_경로로_이어진다():
    idx = docidkey.OverrideIndex({"D:/폴더/e.doc": {"doc_id": None, "hash": H}})
    # 구분자 표기만 다른 같은 경로 — key 칸 없이 file 만 준다.
    got, how = idx.resolve({"file": r"D:\폴더\e.doc"})
    assert (got, how) == ("D:/폴더/e.doc", "path")
