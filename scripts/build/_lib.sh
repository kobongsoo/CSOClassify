#------------------------------------------------------------------
# 빌드 스크립트 공통 — 실패하면 즉시 멈춘다
#=> 2026-09-11 배포 때, 실패한 명령 다음 줄이 그대로 실행돼 배포 폴더의
#   파이썬 런타임(_internal)이 잠깐 사라진 일이 있었다. 순서가 이랬다:
#     ① mv _internal      _internal.old   → 성공
#     ② mv _internal.new  _internal       → Permission denied (파일 잠김)
#     ③ rm -rf _internal.old              → ②가 실패했는데도 그냥 실행
#   ②가 실패한 순간 멈췄어야 했다. 즉석 셸로 치면 이런 일이 반복되므로
#   절차를 파일로 남기고, 그 파일이 실패에서 멈추게 한다.
#
# 쓰는 법: 각 스크립트 맨 위에서
#   . "$(dirname "$0")/_lib.sh"
#------------------------------------------------------------------

# -e : 명령 하나라도 실패하면 즉시 종료
# -u : 안 정한 변수를 쓰면 종료(오타로 빈 경로를 지우는 사고를 막는다)
# -o pipefail : 파이프 중간이 실패해도 잡는다(`cmd | tail` 에서 cmd 실패가 묻히지 않게)
set -euo pipefail


#------------------------------------------------------------------
# 실패 알림 후 종료
#=> 어디서 왜 멈췄는지 한 줄로 남긴다. 빌드는 몇 분씩 걸려, 로그를
#   거슬러 올라가며 원인을 찾는 일이 잦다.
#
# -in: $* = 사람이 읽는 실패 사유
#
# -out: 없음(종료코드 1 로 끝낸다)
#------------------------------------------------------------------
die() {
    echo "" >&2
    echo "[실패] $*" >&2
    echo "       (여기서 멈춥니다 — 뒤 단계는 실행하지 않습니다)" >&2
    exit 1
}


#------------------------------------------------------------------
# 단계 표시
#=> 긴 빌드에서 지금 어디인지 보이게 한다.
#
# -in: $* = 단계 이름
#
# -out: 없음(화면 출력)
#------------------------------------------------------------------
step() {
    echo ""
    echo "── $* ──────────────────────────────────────────"
}


#------------------------------------------------------------------
# 예기치 못한 종료를 알린다
#=> set -e 로 멈출 때는 사유가 안 찍힌다. 어느 줄에서 멈췄는지라도 남긴다.
#------------------------------------------------------------------
# ${..:-} 로 감싼다 — set -u 아래에서 BASH_SOURCE 가 없는 자리(대화형 source 등)
# 에서 트랩 자체가 "unbound variable" 로 터지면, 정작 알리려던 실패가 가려진다.
trap 'rc=$?; if [ $rc -ne 0 ]; then echo "" >&2; echo "[중단] ${BASH_SOURCE[0]:-$0}:${LINENO:-?} 에서 종료코드 $rc" >&2; fi; exit $rc' ERR


#------------------------------------------------------------------
# 폴더를 안전하게 갈아 끼운다 (되돌릴 수 있게)
#=> 배포 폴더의 무거운 하위 폴더(_internal 등)를 새것으로 바꾼다.
#   중간에 실패하면 **옛것을 되돌리고 멈춘다** — 빈 배포 폴더를 남기지 않는다.
#    1) 새것이 멀쩡한지 먼저 본다(없거나 비어 있으면 아무것도 건드리지 않는다)
#    2) 옛것을 .bak-<시각> 으로 옮긴다
#    3) 새것을 제자리로 옮긴다 — 실패하면 옛것을 되돌리고 종료
#    4) 여기까지 오면 .bak 경로를 표준출력으로 알려 준다(지울지는 부르는 쪽이 정한다)
#
# -in: $1 = 새 폴더 경로(갈아 끼울 것)
# -in: $2 = 제자리 경로(갈아 끼워질 자리)
#
# -out: 표준출력에 백업 경로 한 줄(옛것이 없었으면 빈 줄)
# -out: error = 새것이 이상하거나 갈아 끼우기에 실패하면 종료코드 1
#------------------------------------------------------------------
swap_dir() {
    local new="$1" dst="$2"
    local bak=""

    [ -d "$new" ] || die "새 폴더가 없습니다: $new"
    [ "$(find "$new" -mindepth 1 -maxdepth 1 | head -1)" ] \
        || die "새 폴더가 비어 있습니다: $new"

    if [ -e "$dst" ]; then
        bak="${dst}.bak-$(date +%Y%m%d-%H%M%S)"
        mv "$dst" "$bak" || die "옛 폴더를 옮기지 못했습니다: $dst"
    fi

    # 여기서 실패하면 배포 폴더에 그 칸이 비게 된다 — 반드시 되돌린다.
    if ! mv "$new" "$dst"; then
        if [ -n "$bak" ]; then
            mv "$bak" "$dst" && echo "[복구] 옛 폴더를 되돌렸습니다: $dst" >&2
        fi
        die "새 폴더를 제자리로 옮기지 못했습니다: $dst
       (다른 프로그램이 그 폴더를 열고 있을 수 있습니다 — 탐색기·백신·실행 중인 exe)"
    fi
    echo "$bak"
}


#------------------------------------------------------------------
# 빌드서버 설정 읽기
#=> 서버 주소·계정·안쪽 경로는 코드가 아니라 설정이다. 저장소가 공개라
#   코드에 박아 두면 내부 인프라가 그대로 노출된다.
#   값은 scripts/build/server.env 에 두고, 보기는 server.env.sample 에 있다.
#
# -in: $1 = 설정 파일 경로
#
# -out: 없음(읽은 값을 환경변수로 export 한다)
# -out: error = 파일이 없거나 필요한 값이 비면 종료코드 1
#------------------------------------------------------------------
load_server_env() {
    local f="$1"
    [ -f "$f" ] || die "빌드서버 설정이 없습니다: $f
       scripts/build/server.env.sample 을 server.env 로 복사해 값을 채우세요.
       (이 파일은 .gitignore 로 막혀 있어 저장소에 올라가지 않습니다)"
    # 주석·빈 줄을 걸러 KEY=VALUE 만 읽는다. 값에 공백이 있어도 그대로 담는다.
    while IFS='=' read -r k v; do
        case "$k" in ''|\#*) continue ;; esac
        v="${v%$'\r'}"                      # 윈도우에서 편집하면 붙는 캐리지리턴
        export "$k=$v"
    done < "$f"
    for k in BUILD_PY_DIR BUILD_RS_DIR MODEL_SRC_DIR CONDA_ENV_DIR \
             CONDA_PROFILE CONDA_ENV_NAME CARGO_BIN_DIR; do
        eval "[ -n \"\${$k:-}\" ]" || die "빌드서버 설정에 $k 가 없습니다: $f"
    done
}
