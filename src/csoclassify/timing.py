#------------------------------------------------------------------
# 처리 시간 측정 도우미 (설계서 §7-1)
#=> "파일 로딩+파싱(extract) → 정제 → 청킹 → 임베딩" 각 단계 소요시간과
#   총합을 ms 단위로 모아 두는 작은 스톱워치다. 단조시계(perf_counter)를
#   써서 시스템 시각이 바뀌어도 측정이 흔들리지 않게 한다.
#
# -필드: stages = {단계이름: 소요 ms} 딕셔너리
# -필드: _t0    = 전체 시작 시각(총 wall-clock 계산용)
#------------------------------------------------------------------

import time
from contextlib import contextmanager


class Timing:
    #------------------------------------------------------------------
    # 생성자 — 스톱워치 초기화
    #=> 단계별 기록 딕셔너리를 비우고, 전체 시작 시각을 지금으로 잡는다.
    #
    # -in: 없음
    #
    # -out: 없음
    # -out: error = 없음
    #------------------------------------------------------------------
    def __init__(self):
        self.stages = {}
        self._t0 = time.perf_counter()

    #------------------------------------------------------------------
    # 단계 시간 측정 컨텍스트매니저
    #=> `with t.measure("embed"):` 로 감싼 구간의 소요시간을 자동으로 재서
    #   stages["embed"] 에 ms 로 누적한다. 같은 이름을 여러 번 재면 더해진다.
    #
    # -in: name = 단계 이름 (예: "extract", "embed")
    #
    # -out: 없음 (with 블록을 감쌈)
    # -out: error = 블록 내부 예외는 그대로 전파(시간은 finally 에서 기록됨)
    #------------------------------------------------------------------
    @contextmanager
    def measure(self, name):
        start = time.perf_counter()
        try:
            yield
        finally:
            # 예외가 나도 여기까지 걸린 시간은 기록해 둔다(디버깅에 유용).
            elapsed_ms = (time.perf_counter() - start) * 1000.0
            self.stages[name] = self.stages.get(name, 0.0) + elapsed_ms

    #------------------------------------------------------------------
    # 단계 값 직접 기록
    #=> 데몬이 보내온 단계별 시간처럼, 이미 측정된 ms 값을 그대로 넣을 때 쓴다.
    #
    # -in: name = 단계 이름
    # -in: ms   = 소요 밀리초
    #
    # -out: 없음
    # -out: error = 없음
    #------------------------------------------------------------------
    def set(self, name, ms):
        self.stages[name] = float(ms)

    #------------------------------------------------------------------
    # 전체 경과시간 확정
    #=> 생성 시점부터 지금까지의 wall-clock 을 total 로 확정해 반환한다.
    #
    # -in: 없음
    #
    # -out: total_ms = 전체 경과 밀리초 (stages["total"] 에도 저장)
    # -out: error = 없음
    #------------------------------------------------------------------
    def finalize_total(self):
        total = (time.perf_counter() - self._t0) * 1000.0
        self.stages["total"] = total
        return total

    #------------------------------------------------------------------
    # 소수 둘째자리로 반올림한 사본
    #=> 출력용으로 보기 좋게 반올림한 {단계: ms} 딕셔너리를 만든다.
    #
    # -in: 없음
    #
    # -out: dict = 반올림된 단계별 ms
    # -out: error = 없음
    #------------------------------------------------------------------
    def as_dict(self):
        return {k: round(v, 2) for k, v in self.stages.items()}
