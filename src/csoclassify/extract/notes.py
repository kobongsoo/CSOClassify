#------------------------------------------------------------------
# 추출 부가정보 전달 통로 (G5 관측용)
#=> "이 문서는 끝까지 못 읽고 상한에서 멈췄다"를 파서에서 결과 레코드까지
#   전달하기 위한 자리다.
#
#   [왜 이런 게 필요한가] 파서(pdf_pdfium 등)는 문자열 하나만 돌려주도록
#   약속돼 있다(TextExtractor.extract). 그런데 상한에 걸려 앞부분만 읽었다는
#   사실은 '본문'이 아니라 '본문에 대한 사실'이라 그 문자열에 담을 수가 없다.
#   그렇다고 반환형을 (텍스트, 부가정보) 튜플로 바꾸면 추출기 11개와 그것을
#   부르는 모든 자리가 함께 바뀐다 — 상한 하나 때문에 인터페이스를 갈아엎는 셈이다.
#   그래서 파서가 여기에 적어 두고, 부른 쪽이 가져가는 방식으로 뒀다.
#
#   [왜 스레드 로컬인가] 데몬은 여러 요청을 스레드로 받을 수 있다. 전역 변수
#   한 칸에 적으면 A 문서의 '부분 추출' 표식이 B 문서 결과에 붙는다. 그런
#   오염은 조용히 일어나 추적이 거의 불가능하므로, 처음부터 스레드마다 따로 둔다.
#
#   [사용 규약] 부르는 쪽이 extract() 직전에 reset(), 직후에 take() 한다.
#   take() 는 값을 가져가면서 비우므로, 다음 문서에 지난 표식이 남지 않는다.
#------------------------------------------------------------------

import threading

_state = threading.local()


#------------------------------------------------------------------
# 표식 비우기
#=> 추출을 시작하기 전에 부른다. 이전 문서(또는 폴백으로 버려진 엔진)가 남긴
#   표식이 이번 결과에 섞이지 않게 한다.
#
# -in: 없음
#
# -out: 없음
# -out: error = 없음
#------------------------------------------------------------------
def reset():
    _state.partial = None


#------------------------------------------------------------------
# '상한에서 멈췄다' 적어 두기
#=> 페이지·시트 루프가 상한에 걸려 중단됐을 때 파서가 부른다. 실패가 아니라
#   '부분 성공'이므로 예외를 던지지 않고 이 표식만 남긴다.
#
# -in: reason = 왜 멈췄나(예: "페이지 상한(3000p)")
# -in: unit   = 세는 단위 이름(예: "pages", "sheets", "slides")
# -in: read   = 실제로 읽은 개수
# -in: total  = 원래 있던 전체 개수(모르면 None)
#
# -out: 없음
# -out: error = 없음
#------------------------------------------------------------------
def set_partial(reason, unit, read, total=None):
    _state.partial = {"reason": reason, "unit": unit, "read": read, "total": total}


#------------------------------------------------------------------
# 표식 가져가며 비우기
#=> 추출이 끝난 직후 부르는 쪽이 한 번 가져간다. 가져가면서 비우므로 같은
#   표식을 두 문서가 나눠 갖는 일이 없다.
#
# -in: 없음
#
# -out: dict | None = {reason, unit, read, total} 또는 표식 없음(None)
# -out: error = 없음
#------------------------------------------------------------------
def take():
    note = getattr(_state, "partial", None)
    _state.partial = None
    return note
