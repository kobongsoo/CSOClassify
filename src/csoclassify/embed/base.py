#------------------------------------------------------------------
# 임베더 공통 인터페이스
#=> "정제된 텍스트를 주면 임베딩 벡터를 돌려준다"는 약속을 정의한다. 모델 로딩은
#   무거우므로 ensure_loaded() 로 분리해, 필요할 때(또는 미리 예열) 로드하게 한다.
#------------------------------------------------------------------

from abc import ABC, abstractmethod


#------------------------------------------------------------------
# 임베딩 실패 예외
#=> 모델 파일 없음/로딩 실패/빈 텍스트 등 벡터를 못 만든 경우를 묶는 예외.
#
# -필드: (메시지 문자열만 사용)
#------------------------------------------------------------------
class EmbedError(Exception):
    pass


#------------------------------------------------------------------
# 임베더 추상 클래스
#=> 로딩(ensure_loaded)과 문서 임베딩(embed_document)을 강제한다.
#
# -필드: 없음(순수 인터페이스)
#------------------------------------------------------------------
class Embedder(ABC):
    #------------------------------------------------------------------
    # 모델 적재 보장(지연 로딩)
    #=> 아직 안 올라왔으면 모델/토크나이저를 메모리에 올린다. 이미 올라와 있으면
    #   아무 것도 하지 않는다(idempotent). 단일파일 처리 시 추출과 병렬로 미리
    #   호출해 콜드 스타트를 가리는 데 쓴다.
    #
    # -in: 없음
    #
    # -out: load_ms = 이번 호출에서 실제 로딩에 걸린 밀리초(이미 로드면 0.0)
    # -out: error = 모델 파일 없음/로딩 실패 시 EmbedError
    #------------------------------------------------------------------
    @abstractmethod
    def ensure_loaded(self):
        raise NotImplementedError

    #------------------------------------------------------------------
    # 문서 텍스트 → 벡터
    #=> 텍스트를 청킹·임베딩하고, 기본은 청크 평균으로 문서 1벡터를 만든다.
    #
    # -in: text      = 정제된 문서 텍스트
    # -in: max_tokens= 청크 최대 토큰
    # -in: overlap   = 청크 겹침 토큰
    # -in: normalize = True 면 L2 정규화
    # -in: per_chunk = True 면 문서벡터 대신 청크별 벡터 리스트 반환
    #
    # -out: (vector_or_list, n_chunks) = 벡터(list[float]) 또는 청크벡터들, 청크 수
    # -out: error = 빈 텍스트/추론 실패 시 EmbedError
    #------------------------------------------------------------------
    @abstractmethod
    def embed_document(self, text, max_tokens, overlap, normalize=True, per_chunk=False):
        raise NotImplementedError
