# 확신도(0~1 소수) → "85%" 표기
#=> 0.85 같은 소수는 읽는 데 시간이 걸린다. 정수 퍼센트로 바꿔 표에서 바로 읽히게 한다.
#
# -in: conf = 신뢰도(0.0~1.0). None 이면 빈 문자열
#
# -out: str = "85%" 또는 ""(값이 없을 때)
# -out: error = 없음(숫자가 아니면 빈 문자열)
#------------------------------------------------------------------
def pct(conf):
    try:
        return f"{round(float(conf) * 100)}%"
    except (TypeError, ValueError):
        return ""


#------------------------------------------------------------------
# 업무분류 후보 1개 → 화면 표기
#=> 자동 제안도 '확정'으로 보므로(관리자가 바꾸기 전까지) 표에는 경로만 적는다.
#   예전에는 확정 전 제안 뒤에 "?" 를 붙였는데, 이제 확정이 기본이라 모든 줄에
#   물음표가 붙어 뜻이 없어졌다. "사람이 확인했는가"는 상세 화면에서 알린다.
#
# -in: cand = doctype_review.effective_doctype() 가 만든 후보 dict
#             ({path, confidence, status, ...})
#
# -out: str = 예 "법무/규정 > 계약서" 또는 "영업/마케팅 > 제안서 ?"
# -out: error = 없음(값이 없으면 dc_id 로 대체)
#------------------------------------------------------------------
def doctype_chip(cand):
    label = cand.get("path") or cand.get("dc_id") or "?"
    return label if cand.get("status") == "confirmed" else f"{label} ?"


#------------------------------------------------------------------
# 업무분류 한 건이 '누가 정한 것인지' 한 마디
#=> 자동 확정과 사람이 확정한 것을 화면에서 구분한다. 거버넌스 도구에서 "이 분류를
#   누가 정했는가"는 지워지면 안 되는 정보다.
#
# -in: cand = 후보 dict(auto 키를 본다)
#
# -out: str = "자동 확정" 또는 "관리자 확정"("아니라고 표시함"이면 그 말)
# -out: error = 없음
#------------------------------------------------------------------
def doctype_by(cand):
    if (cand or {}).get("status") == "rejected":
        return STATUS_LABEL["rejected"]
    return "자동 확정" if (cand or {}).get("auto") else "관리자 확정"


#------------------------------------------------------------------
# 업무분류 후보 여러 개 → 표 한 칸에 넣을 요약 문자열
#=> 표가 세로로 길어지지 않도록 앞의 몇 개만 보여주고 나머지는 "+N" 으로 접는다.
#   저장은 전부 하고 화면만 줄이는 원칙이다(설계서 7-1 · 상위 설계 6-3).
#   거절(rejected)한 후보는 표에 아예 내지 않는다 — 사람이 이미 아니라고 한 것이다.
#
# -in: candidates = 후보 리스트(effective_doctype 결과)
# -in: limit      = 표에 직접 보여줄 최대 개수(기본 2)
#
# -out: str = 예 "법무/규정 > 계약서 · 영업 > 제안서 ? +2" / 후보 없으면 "— 없음"
# -out: error = 없음
#------------------------------------------------------------------
def doctype_cell(candidates, limit=2):
    alive = [c for c in (candidates or []) if c.get("status") != "rejected"]
    if not alive:
        return "— 없음"
    # 확정된 것을 먼저 보여준다 — 사람이 정한 사실이 기계 제안보다 중요하다.
    alive.sort(key=lambda c: (c.get("status") != "confirmed",
                              -float(c.get("confidence") or 0)))
    head = " · ".join(doctype_chip(c) for c in alive[:limit])
    rest = len(alive) - limit
    return f"{head} +{rest}" if rest > 0 else head


#------------------------------------------------------------------
# 문서 한 건의 "할 일" 상태 한 줄
#=> 두 축을 한 칸에 합쳐, 이 문서에 사람이 손댈 것이 남았는지를 알려준다.
#   보안등급 확인이 필요하면 그쪽을 먼저 말한다 — 덜 보호하는 실수가 더 비싸므로
#   화면에서도 보안이 앞선다(상위 설계 2-1).
#
# -in: need_sec = 보안등급 확인이 필요한가(판단 못 함 또는 저확신)
# -in: need_doc = 업무분류가 아직 하나도 없는가(기계가 못 맞혀 사람이 직접 정해야 함)
#
# -out: str = "⚠ 등급 확인 필요" / "분류 확인 필요" / "⚠ 등급/분류 확인 필요" / "✅ 확정됨"
# -out: error = 없음
#------------------------------------------------------------------
def todo_label(need_sec, need_doc):
    # need_doc 은 '업무분류가 하나도 안 붙은 문서'를 뜻한다(제안을 확정하는 것이
    # 아니라 사람이 직접 정해야 하는 상태) — 표현도 '대기'가 아니라 '확인'으로 맞춘다.
    if need_sec and need_doc:
        return "⚠ 등급/분류 확인 필요"
    if need_sec:
        return "⚠ 등급 확인 필요"
    if need_doc:
        return "분류 확인 필요"
    return "✅ 확정됨"
