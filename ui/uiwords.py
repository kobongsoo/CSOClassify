# 등급 값 정규화(None·이상값 → "보류")
#=> 레코드의 grade 는 None 일 수 있는데, 표·집계에서 다루기 쉽게 "보류" 키로 모은다.
#   화면에는 GRADE_LABEL 을 거쳐 "판단 못 함"으로 나간다.
#
# -in: g = 등급 값("C"/"S"/"O"/None/그 밖)
#
# -out: str = "C"/"S"/"O"/"보류"
# -out: error = 없음(항상 문자열 반환)
#------------------------------------------------------------------
def norm_grade(g):
    return g if g in ("C", "S", "O") else "보류"


#------------------------------------------------------------------
# 등급 → 화면 배지 문자열
#=> "🔴 C 기밀" 처럼 색·알파벳·한글 3중 표기로 만든다. 색만으로 구분되는 정보를
#   만들지 않기 위한 규칙이다(설계서 14장 접근성 — 색각 이상 대응).
#
# -in: g       = 등급 값(정규화 전이어도 됨)
# -in: emoji   = False 면 이모지를 빼고 "C 기밀" 만 (기본 True)
#
# -out: str = 화면에 그대로 쓸 수 있는 배지 문자열
# -out: error = 없음
#------------------------------------------------------------------
def grade_badge(g, emoji=True):
    g = norm_grade(g)
    return GRADE_LABEL[g] if emoji else GRADE_PLAIN[g]


